    public static string Get(string language, string key) => Strings[Language.FromTag(language)][key];

    public static string Get(string language, string key, params object[] args) =>
        string.Format(CultureInfo.GetCultureInfo(Language.FromTag(language)), Get(language, key), args.Select(value => value is string text ? (object)DisplayText.Clean(text) : value).ToArray());

    public static AdbException AdbError(string key, params object[] args)
    {
        var exception = new AdbException(Get("ko", key, args));
        exception.Data["message_key"] = key;
        exception.Data["message_args"] = args;
        return exception;
    }

    public static AdbNotFoundException MissingAdb(Exception inner)
    {
        var exception = new AdbNotFoundException(Get("ko", "adb_missing"), inner);
        exception.Data["message_key"] = "adb_missing";
        exception.Data["message_args"] = Array.Empty<object>();
        return exception;
    }

    public static string Error(string language, AdbException exception) =>
        exception.Data["message_key"] is string key
            ? Get(language, key, exception.Data["message_args"] as object[] ?? Array.Empty<object>())
            : Get(language, "adb_command", exception.Message);

    public static string Source(string language, string source) => source switch
    {
        BatteryInfo.CycleEstimateSource => Get(language, "source_estimate"),
        "sysfs fg_asoc (보조값)" => Get(language, "source_sysfs"),
        _ => source,
    };
